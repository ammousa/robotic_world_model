"""Compose illustrative, time-aligned replay tiles without predictions or physics.

Input JSON lists B0, B1, B2 and E3_direct_velocity replay/status paths plus
immutable scored-artifact references. B3 uses B2's identical bytes by definition.
Censored clips freeze with a visible end-reason banner; they never gain states.
"""

import argparse
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path


def digest(path):
    h = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(8 * 1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def compose(manifest, output):
    assert manifest["kind"] == "illustrative_kinematic_replay_comparison"
    assert manifest["mode"] in ("A", "B")
    assert manifest["fps"] == 50 and manifest["duration_s"] == 30
    variants = ["B0", "B1", "B2", "B3_accel", "E3_direct_velocity"]
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    commands = ["ffmpeg", "-hide_banner", "-loglevel", "warning", "-nostdin", "-y"]
    filters, sources = [], []
    with tempfile.TemporaryDirectory(prefix="rwm_replay_tiles_") as temporary:
        temporary = Path(temporary)
        for index, variant in enumerate(variants):
            source_variant = "B2" if variant == "B3_accel" else variant
            source = manifest["sources"][source_variant]
            assert source["scored_artifact"] and source["scored_artifact_digest"]
            status_path, video_path = Path(source["status"]), Path(source["video"])
            status = json.loads(status_path.read_text())
            assert status["kind"] == "illustrative_kinematic_replay_of_scored_arrays"
            assert status["episode_id"] == manifest["episode_id"] and status["physics_steps"] == 0
            assert status["dataset_sha256"] == manifest["dataset_sha256"]
            frames = int(status["frames"])
            if frames:
                assert video_path.is_file() and digest(video_path) == status["video_sha256"]
                commands += ["-i", str(video_path)]
            else:
                commands += ["-f", "lavfi", "-i", "color=c=black:s=640x360:r=50:d=30"]
            label = variant + (" = B2 (same replay; no separate training)" if variant == "B3_accel" else "")
            label_path = temporary / f"label_{index}.txt"
            label_path.write_text(label)
            ended_path = temporary / f"ended_{index}.txt"
            ended_path.write_text(f"Replay ended: {status['end_reason']} at {frames / 50:.2f} s; held frame")
            # textfile paths are generated by TemporaryDirectory and contain no
            # user text or shell interpolation. ffmpeg runs via an argv list.
            graph = (
                f"[{index}:v]setpts=PTS-STARTPTS,fps=50,scale=640:360:force_original_aspect_ratio=decrease,"
                "pad=640:400:(ow-iw)/2:40:black,tpad=stop_mode=clone:stop_duration=30,"
                "trim=duration=30,setpts=PTS-STARTPTS,"
                f"drawtext=textfile={label_path}:fontcolor=white:fontsize=18:x=8:y=10"
            )
            if frames < 1500:
                graph += (
                    f",drawtext=textfile={ended_path}:fontcolor=yellow:fontsize=15:x=8:y=373:"
                    f"box=1:boxcolor=black@0.9:enable='gte(t,{frames / 50:.8f})'"
                )
            filters.append(graph + f"[tile{index}]")
            sources.append(
                {
                    "tile": variant,
                    "source_variant": source_variant,
                    "source": source,
                    "status": status,
                    "status_sha256": digest(status_path),
                }
            )
        legend = temporary / "legend.txt"
        semantics = (
            "A: identical recorded future actions"
            if manifest["mode"] == "A"
            else "B: same commands; each model chooses actions"
        )
        legend.write_text(
            "ILLUSTRATIVE REPLAY OF FIXED SCORED ARRAYS\n"
            + semantics
            + "\n"
            + f"Seed {manifest['training_seed']}; episode {manifest['episode_id']}; 50 Hz\n"
            + "Each tile: reference and imagined actor\n"
            + "B3 acceleration is the B2 equality control\n"
            + "Held frames after an end are not predictions\n"
            + "No physics or model inference in this composition"
        )
        filters.append(
            "color=c=black:s=640x400:r=50:d=30,"
            f"drawtext=textfile={legend}:fontcolor=white:fontsize=18:x=12:y=45:line_spacing=12[legend]"
        )
        filters.append(
            "[tile0][tile1][tile2][tile3][tile4][legend]xstack=inputs=6:"
            "layout=0_0|640_0|0_400|640_400|0_800|640_800[out]"
        )
        commands += [
            "-filter_complex_threads",
            "1",
            "-filter_complex",
            ";".join(filters),
            "-map",
            "[out]",
            "-an",
            "-c:v",
            "libx264",
            "-preset",
            "fast",
            "-crf",
            "22",
            "-threads",
            "2",
            "-pix_fmt",
            "yuv420p",
            "-t",
            "30",
            str(output),
        ]
        subprocess.run(commands, check=True)
    record = {
        "kind": manifest["kind"],
        "mode": manifest["mode"],
        "episode_id": manifest["episode_id"],
        "training_seed": manifest["training_seed"],
        "fps": 50,
        "duration_s": 30,
        "physics_steps": 0,
        "neural_forward_calls": 0,
        "new_scored_units": 0,
        "sources": sources,
        "output_sha256": digest(output),
    }
    output.with_suffix(".json").write_text(json.dumps(record, indent=2) + "\n")
    return record


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = compose(json.loads(args.manifest.read_text()), args.output)
    print(
        json.dumps(
            {
                "output": str(args.output),
                "sha256": result["output_sha256"],
                "kind": result["kind"],
                "new_scored_units": 0,
            }
        )
    )
